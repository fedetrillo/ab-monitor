const LANGS = Object.keys(I18N);

/** The language to start in: the saved one, else the system's, else English. */
function pickLanguage(saved, navLangs = (typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [])) {
  if (saved && I18N[saved]) return saved;
  for (const l of navLangs) {
    const code = String(l ?? '').toLowerCase().split('-')[0];
    if (I18N[code]) return code;
  }
  return 'en';
}

/** A text in `lang`, with `{name}` placeholders filled from `vars`. Falls back to English. */
function translate(lang, key, vars = {}) {
  const s = I18N[lang]?.[key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

globalThis.AddOnI18n = { I18N, LANGS, pickLanguage, translate };
